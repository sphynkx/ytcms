_SUPPORTED = {"int8", "float32"}

def _sanitize_compute_type(ct: str) -> str:
    return ct if ct in _SUPPORTED else "int8"

def _safe_progress(cb: Callable[[float], None], value: float) -> None:
    try:
        cb(value)
    except Exception:
        pass

def _fmt_pct(x: float) -> str:
    try:
        return f"{x*100:.1f}%"
    except Exception:
        return "?"

# ---------------- ffmpeg helpers ----------------

def _ffprobe_duration_sec(path: str) -> float:
    try:
        cmd = ["ffprobe", "-v", "error", "-show_entries", "format=duration",
               "-of", "default=noprint_wrappers=1:nokey=1", path]
        out = subprocess.check_output(cmd, stderr=subprocess.STDOUT, timeout=10)
        s = (out.decode("utf-8", "ignore").strip() or "0")
        return max(0.0, float(s))
    except Exception:
        return 0.0

def _ffmpeg_extract_wav_chunk(src: str, start: float, dur: float, out_path: str, lookbehind: float = 0.0) -> Tuple[bool, float]:
    try:
        real_start = max(0.0, start - max(0.0, lookbehind))
        t = max(0.01, dur + (start - real_start))
        cmd = [
            "ffmpeg", "-y",
            "-ss", f"{real_start:.3f}",
            "-t", f"{t:.3f}",
            "-i", src,
            "-vn",
            "-ac", "1",
            "-ar", "16000",
            "-f", "wav",
            out_path,
        ]
        subprocess.check_call(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=max(10, int(t*5)))
        return (os.path.exists(out_path) and os.path.getsize(out_path) > 0, real_start)
    except Exception:
        return (False, start)

# ---------------- Text heuristics ----------------

_ACCENT_FR = set("àâäæçéèêëîïôœùûüÿ’")
_CJK_BLOCK = lambda ch: ord(ch) >= 0x2E80

def _looks_like_disclaimer(text: str) -> bool:
    t = (text or "").strip()
    if not t or len(t) > 120:
        return False
    lower = t.lower()
    patterns = [
        r"^transcribed by\b",
        r"^auto(\-|\s)?generated\b",
        r"^generated by\b",
        r"^captions by\b",
        r"^subtitles by\b",
        r"^.*(auto[-\s]?transcription).*",
    ]
    return any(re.search(p, lower) for p in patterns)

def _analyze_chars(text: str) -> Dict[str, Any]:
    accents = sum(1 for c in text if c in _ACCENT_FR)
    latin = sum(1 for c in text if 'a' <= c.lower() <= 'z')
    cjk = sum(1 for c in text if _CJK_BLOCK(c))
    total = len(text)
    return {
        "accents": accents,
        "latin": latin,
        "cjk": cjk,
        "total": total,
        "accent_ratio": (accents / total) if total else 0.0,
        "cjk_ratio": (cjk / total) if total else 0.0,
        "latin_ratio": (latin / total) if total else 0.0,
    }

def _should_correct_lang(lang: str, prev_lang: str, text: str) -> Optional[str]:
    stats = _analyze_chars(text)
    if lang in ("zh", "ja", "ko") and stats["cjk"] == 0 and stats["latin_ratio"] > 0.6:
        return prev_lang if prev_lang not in ("unknown", "") else "en"
    if lang == "es" and stats["accent_ratio"] > 0.03 and stats["accents"] >= 5:
        return "fr"
    if lang == "en" and stats["accent_ratio"] > 0.03 and stats["accents"] >= 5:
        return "fr" if prev_lang in ("fr", "en", "unknown") else prev_lang
    return None

def _is_noise_segment(text: str) -> bool:
    t = (text or "").strip()
    if not t:
        return True
    if len(t) >= 3 and all(ch in "_-." for ch in t):
        return True
    non_word = sum(1 for c in t if not c.isalnum())
    if non_word / len(t) > 0.8 and len(t) <= 25:
        return True
    return False

# ---------------- Splitting ----------------

def _split_segment_by_words(seg: Dict[str, Any], max_len_sec: float, words: List[Dict[str, Any]],
                            max_chars: int, subseg_max_sec: float) -> List[Dict[str, Any]]:
    start = seg["start"]; end = seg["end"]
    dur = end - start
    text = seg["text"].strip()
    if (dur <= max_len_sec and len(text) <= max_chars) or not words:
        return [seg]
    out: List[Dict[str, Any]] = []
    current_words: List[Dict[str, Any]] = []
    current_start = None
    def flush():
        nonlocal current_words, current_start
        if not current_words:
            return
        cs = current_start
        ce = current_words[-1]["end"]
        txt = " ".join(w["word"] for w in current_words).strip()
        out.append({"start": cs, "end": ce, "text": txt})
        current_words = []; current_start = None
    for w in words:
        if current_start is None:
            current_start = w["start"]
        next_len = len(" ".join([wd["word"] for wd in current_words] + [w["word"]]).strip())
        if ((w["end"] - current_start) > subseg_max_sec) or (next_len > max_chars):
            flush()
            current_start = w["start"]
        current_words.append(w)
    flush()
    final_out: List[Dict[str, Any]] = []
    for piece in out:
        pdur = piece["end"] - piece["start"]
        if pdur <= max_len_sec:
            final_out.append(piece); continue
        parts = max(2, int(math.ceil(pdur / max_len_sec)))
        words_piece = piece["text"].split()
        per = max(1, int(math.ceil(len(words_piece) / parts)))
        wi = 0; chunk_dur = pdur / parts
        for i in range(parts):
            cs = piece["start"] + i * chunk_dur
            ce = piece["start"] + (i + 1) * chunk_dur
            wchunk = words_piece[wi: wi + per]; wi += per
            final_out.append({"start": cs, "end": ce, "text": " ".join(wchunk).strip()})
    return final_out

def _split_long_segments(segs: List[Dict[str, Any]], words_map: Dict[int, List[Dict[str, Any]]],
                         max_len_sec: float, max_chars: int, subseg_max_sec: float) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    for idx, s in enumerate(segs):
        start = float(s["start"]); end = float(s["end"])
        dur = end - start
        text = s["text"].strip()
        if dur <= max_len_sec and len(text) <= max_chars:
            out.append(s); continue
        wlist = words_map.get(idx, [])
        if wlist:
            out.extend(_split_segment_by_words(s, max_len_sec, wlist, max_chars, subseg_max_sec))
        else:
            words = text.split()
            if not words:
                continue
            pieces = max(2, int(math.ceil(len(text) / max_chars)))
            chunk_dur = dur / pieces
            per = max(1, int(math.ceil(len(words) / pieces)))
            wi = 0
            for i in range(pieces):
                cs = start + i * chunk_dur
                ce = start + (i + 1) * chunk_dur
                wchunk = words[wi: wi + per]; wi += per
                out.append({"start": cs, "end": ce, "text": " ".join(wchunk).strip()})
    return out

def _drop_leading_disclaimer(segs: List[Dict[str, Any]], max_at_sec: float = 4.0) -> List[Dict[str, Any]]:
    while segs and float(segs[0].get("start", 0.0)) <= max_at_sec and _looks_like_disclaimer(segs[0].get("text", "")):
        segs = segs[1:]
    cleaned: List[Dict[str, Any]] = []
    for s in segs:
        if float(s.get("start", 0.0)) <= max_at_sec and _looks_like_disclaimer(s.get("text", "")):
            continue
        cleaned.append(s)
    return cleaned

def _filter_noise_segments(segs: List[Dict[str, Any]], enabled: bool) -> List[Dict[str, Any]]:
    if not enabled:
        return segs
    return [s for s in segs if not _is_noise_segment(s.get("text", ""))]

# ---------------- LID (fastText) ----------------

class _LID:
    def __init__(self, path: str):
        self.ok = False
        self.model = None
        if not fasttext or not path or not os.path.isfile(path):
            print("[ytcms] LID disabled (fastText not available or model path missing)")
            return
        try:
            self.model = fasttext.load_model(path)
            self.ok = True
            print(f"[ytcms] LID loaded model={path}")
        except Exception as e:
            print(f"[ytcms] LID load failed: {e}")
            self.ok = False

    def predict(self, text: str) -> Tuple[str, float]:
        if not self.ok or not self.model:
            return ("unknown", 0.0)
        try:
            # FastText expects clean text
            t = (text or "").strip()
            if not t:
                return ("unknown", 0.0)
            labels, scores = self.model.predict(t, k=1)
            if not labels or not scores:
                return ("unknown", 0.0)
            lab = labels[0]  # '__label__fr'
            lang = lab.replace("__label__", "")
            score = float(scores[0])
            return (lang, score)
        except Exception:
            return ("unknown", 0.0)

